function slugify(value) {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s-_]/g, '')
    .trim()
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-') || 'untitled';
}

function convertMonthYearToYearMonth(slug) {
  const match = slug.match(/^(\d{2})-(\d{2})$/);
  if (!match) {
    return null;
  }

  const month = Number(match[1]);
  if (month < 1 || month > 12) {
    return null;
  }

  return `${match[2]}-${match[1]}`;
}

function convertYearMonthToMonthYear(slug) {
  const match = slug.match(/^(\d{2})-(\d{2})$/);
  if (!match) {
    return null;
  }

  const month = Number(match[2]);
  if (month < 1 || month > 12) {
    return null;
  }

  return `${match[2]}-${match[1]}`;
}

function resolveLegacySlug(slug, canonicalSlugs) {
  if (canonicalSlugs.has(slug)) {
    return slug;
  }

  const mmYy = convertMonthYearToYearMonth(slug);
  if (mmYy && canonicalSlugs.has(mmYy)) {
    return mmYy;
  }

  const hashedMatch = slug.match(/^(.*)-[a-f0-9]{8,}$/);
  if (hashedMatch) {
    const base = hashedMatch[1];
    if (canonicalSlugs.has(base)) {
      return base;
    }

    const convertedBase = convertMonthYearToYearMonth(base);
    if (convertedBase && canonicalSlugs.has(convertedBase)) {
      return convertedBase;
    }
  }

  return null;
}

async function getCanonicalSlugs() {
  const entries = await fs.readdir(BLOG_DIR, { withFileTypes: true });
  return new Set(
    entries
      .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== '_index.md')
      .map((entry) => slugify(path.basename(entry.name, path.extname(entry.name))))
  );
}

async function run() {
  const canonicalSlugs = await getCanonicalSlugs();
  const rules = new Map();

  for (const slug of canonicalSlugs) {
    const monthYearAlias = convertYearMonthToMonthYear(slug);
    if (monthYearAlias && monthYearAlias !== slug) {
      rules.set(`/blog/${monthYearAlias}`, `/blog/${slug}/`);
    }
  }

  for (const legacySlug of legacyBlogSlugs) {
    const resolved = resolveLegacySlug(legacySlug, canonicalSlugs);
    rules.set(`/blog/${legacySlug}`, resolved ? `/blog/${resolved}/` : '/blog/');
  }

  rules.set('/blog/talk-music', '/blog/');
  rules.set('/blog/untitled', '/blog/');

  const lines = ['# Generated by scripts/generate-redirects.mjs'];
  for (const [from, to] of [...rules.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`${from} ${to} 301`);
  }

  lines.push('/tags/markdown* /tags/ 301');
  lines.push('/tags/text* /tags/ 301');
  lines.push('/categories* /blog/ 301');
  lines.push('');

  await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
  await fs.writeFile(OUTPUT, lines.join('\n'), 'utf8');
  process.stdout.write(`Wrote ${OUTPUT}\n`);
}

run().catch((error) => {
  process.stderr.write(`${error.stack || error}\n`);
  process.exitCode = 1;
});
